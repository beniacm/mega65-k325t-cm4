#!/usr/bin/env python3
"""gen_mega65_regs.py -- MEGA65 I/O register names for ca65, from mega65-core's iomap.txt
(generated from the @IO annotations in the VHDL, i.e. the hardware's own names).

    gen_mega65_regs.py <mega65-core>/iomap.txt > mega65_regs.inc

Only the MEGA65-specific ("GS") registers in $D000-$DFFF; units cc65's mega65.inc already names
(SID, CIA1, CIA2) are left out.  Whole-byte registers:  VIC4_SCRNPTRLSB := $D060
Bit fields additionally get a mask:                    VIC4_CHR16 := $D054, VIC4_CHR16_MASK = %00000001
Use:  .include "mega65.inc"  (cc65: C64-compatible VIC/SID/CIA names, zero page)
      .include "mega65_regs.inc"
      lda #VIC4_CHR16_MASK
      tsb VIC4_CHR16
"""
import re
import sys

SKIP_UNITS = {"-", "SUMMARY", "SID", "CIA1", "CIA2", "WRITEONLY", "Buffered", "Hypervisor"}
UNIT_NAMES = {"VIC-IV": "VIC4", "VIC-III": "VIC3", "VIC-II": "VIC2"}


def ident(s):
    s = s.replace("!", "_")
    s = re.sub(r"[^A-Za-z0-9_]", "_", s).strip("_").upper()
    return re.sub(r"_+", "_", s)


def main():
    lines = open(sys.argv[1], encoding="utf-8", errors="replace").read().splitlines()
    rx = re.compile(r"^GS \$(D[0-9A-F]{3})(?:\.(\d)(?:-(\d))?)? (\S+?):(\S+)\s*(.*)$")
    out, seen, skipped = [], {}, 0
    for ln in lines:
        m = rx.match(ln.strip())
        if not m:
            continue
        addr, b0, b1, unit, name, desc = m.groups()
        if unit in SKIP_UNITS:
            continue
        sym = "%s_%s" % (UNIT_NAMES.get(unit, ident(unit)), ident(name))
        desc = re.sub(r"@\S+", "", desc).strip()
        mask = None
        if b0 is not None:
            lo, hi = sorted((int(b0), int(b1) if b1 is not None else int(b0)))
            if (lo, hi) != (0, 7):
                mask = sum(1 << b for b in range(lo, hi + 1))
                desc = "bit%s %s" % ("s %d-%d" % (hi, lo) if hi != lo else " %d" % lo, desc)
        if sym in seen:
            if seen[sym] != (addr, mask):
                skipped += 1                # same name used twice in the map: keep the first
            continue
        seen[sym] = (addr, mask)
        out.append("%-28s := $%s ; %s" % (sym, addr, desc[:90]))
        if mask is not None:
            out.append("%-28s  = %%%s" % (sym + "_MASK", format(mask, "08b")))
    print("; mega65_regs.inc -- MEGA65 I/O register names (generated by gen_mega65_regs.py from")
    print("; mega65-core iomap.txt, i.e. the VHDL @IO annotations).  %d names." % len(seen))
    print("; Use together with cc65's mega65.inc (C64-compatible VIC/SID/CIA names).")
    print(".ifndef MEGA65_REGS_INC")
    print("MEGA65_REGS_INC = 1")
    print("\n".join(out))
    print(".endif")
    if skipped:
        print("gen_mega65_regs: %d later duplicates of a name skipped" % skipped, file=sys.stderr)


if __name__ == "__main__":
    main()
