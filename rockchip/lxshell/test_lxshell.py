#!/usr/bin/env python3
"""Tests of the Linux shell against the Python model of the host master (model.py).

    AEXP=~/projects/mega65/aexp-aga python3 test_lxshell.py [-v]     (or: pytest test_lxshell.py)

Needs an AExp checkout (menu_gen.py reads its config.vhd).  The Kickstart and ADF used here are
generated byte patterns, never real ROMs or disks.  Scratch files go into LXSHELL_TMP (default:
a temporary directory).
"""

import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import hostbus as hb           # noqa: E402
import menu_gen                # noqa: E402
import model as mdl            # noqa: E402
import settings as st          # noqa: E402
import shell as sh             # noqa: E402
import ui                      # noqa: E402

AEXP = os.path.expanduser(os.environ.get('AEXP', '~/projects/mega65/aexp-aga'))
VERBOSE = '-v' in sys.argv

_MENU = None


def menu_data():
    global _MENU
    if _MENU is None:
        _MENU = menu_gen.generate(AEXP)
    return _MENU


class Rig:
    """model + bus + shell + files, with a fake clock"""

    def __init__(self, tmp, kick=True, menu_ok=True, settings=None, model=None, adf_files=('Workbench.adf',)):
        data, mid, defaults = menu_data()
        self.tmp = tmp
        self.menu_path = os.path.join(tmp, 'aexp.menu')
        with open(self.menu_path, 'wb') as f:
            f.write(data if menu_ok else data.replace(b'Amiga 500', b'Amiga 600'))
        self.dir = os.path.join(tmp, 'amiga')
        os.makedirs(self.dir, exist_ok=True)
        self.kick = bytes((i * 7 + (i >> 8)) & 0xFF for i in range(512 << 10))
        if kick:
            with open(os.path.join(self.dir, 'kick.rom'), 'wb') as f:
                f.write(self.kick)
        self.adfs = {}
        for i, name in enumerate(adf_files):
            img = bytes(((j >> 3) + i) & 0xFF for j in range(901120))
            with open(os.path.join(self.dir, name), 'wb') as f:
                f.write(img)
            self.adfs[name] = img
        if settings is not None:
            with open(os.path.join(self.dir, 'amiga.settings'), 'w') as f:
                json.dump(settings, f)
        self.m = model or mdl.ModelMaster(menu_id=mid, defaults=defaults)
        self.bus = hb.HostBus(self.m)
        self.t = [1000.0]
        self.logs = []
        self.state = os.path.join(tmp, 'amiga.state')
        self.sh = sh.AmigaShell(self.bus, self.menu_path, self.dir, card_img=None, state_path=self.state,
                                log=self.logs.append, mono=lambda: self.t[0], wall=lambda: 1.7e9 + self.t[0])
        self.cols, self.ctrl = [0] * 9, 0

    def run(self, seconds=0.0, step=0.01):
        end = self.t[0] + seconds
        acc = 0.0
        while True:
            self.sh.keys(self.cols, self.ctrl, self.t[0])
            wait = self.sh.poll(self.t[0])
            if self.t[0] >= end and (self.sh.task is None or self.sh.want is not None):
                break
            dt = max(step, min(wait, 0.05)) if wait else 0.0005
            self.t[0] += dt
            acc += dt * 1000
            if acc >= 1:
                self.m.tick(int(acc))
                acc -= int(acc)

    def key(self, n, hold=0.06):
        c, r = divmod(n, 8)
        if n in (73, 74):
            self.ctrl |= 0x10 if n == 73 else 0x20
        else:
            self.cols[c] |= 1 << r
        self.run(hold)
        if n in (73, 74):
            self.ctrl &= ~(0x10 if n == 73 else 0x20)
        else:
            self.cols[c] &= ~(1 << r)
        self.run(0.05)

    HELP, RETURN, SPACE, DOWN, UP, RUNSTOP, RIGHT, LEFT = 67, 1, 60, 7, 73, 63, 2, 74

    def screen(self):
        return self.m.screen_text()

    def show(self, title):
        if VERBOSE:
            print('---- ' + title)
            for row in self.screen():
                print('|' + row + '|')


def tmpdir():
    base = os.environ.get('LXSHELL_TMP')
    if base:
        os.makedirs(base, exist_ok=True)
    return tempfile.TemporaryDirectory(dir=base)


def started(r):
    r.sh.attach()
    r.run(1.0)
    return r


# --------------------------------------------------------------------------------------------- tests

def test_generator_defaults():
    data, mid, defaults = menu_data()
    m = json.loads(data)
    assert m['size'] == 94 and len(m['items']) == 94
    # factory defaults: 720p, Lanczos, flicker-free, VGA standard, OSM 100 %, MEGA65 keyboard,
    # Help key, 512K+512K, OCS, no fast RAM, 68000
    on = [n for n in range(94) if defaults[n // 16] >> (n % 16) & 1]
    assert [m['items'][n].strip() for n in on] == [
        '720p 50 Hz 16:9', 'Lanczos', 'HDMI: Flicker-free', 'Standard', '100%', 'MEGA65', 'Help',
        '512K+512K Slow', 'OCS Chipset', 'No Fast RAM', '68000 CPU'], [m['items'][n] for n in on]
    assert mid == menu_gen.zlib.crc32(data) & 0xFFFFFFFF


def test_start():
    with tmpdir() as tmp:
        r = started(Rig(tmp))
        m = r.m
        assert bytes(m.kick[:512 << 10]) == r.kick
        assert not m.held() and m.csr & sh.CSR_RUN_IO == sh.CSR_RUN_IO
        assert not m.csr & hb.CSR_ASCAL_AUTO and not m.csr & hb.CSR_OSM
        assert m.marker == 1
        assert m.cfm == menu_data()[2]
        rel = [e for e in m.events if e[0] == 'release']
        assert len(rel) == 1 and rel[0][1] == menu_data()[2]
        assert not [e for e in m.events if e[0] == 'cfm_while_running']
        flt = json.loads(menu_data()[0])['filter_tables']['LANCZOS2_12']
        assert m.ascal == 4 and m.pphase[:256] == flt and m.pphase[256:512] == flt
        assert m.rtc_toggles == 0, 'clock is opt-in: never written by default'


def test_start_waits_for_kickstart():
    with tmpdir() as tmp:
        r = Rig(tmp, kick=False)
        r.sh.attach()
        r.run(3.0)
        assert r.m.held() and r.m.csr & hb.CSR_OSM
        assert any('Kickstart missing' in row for row in r.screen())
        r.show('kickstart missing')
        with open(os.path.join(r.dir, 'kick.rom'), 'wb') as f:
            f.write(r.kick)
        r.run(2.0)
        assert not r.m.held() and not r.m.csr & hb.CSR_OSM


def test_menu_draw_and_close():
    with tmpdir() as tmp:
        r = started(Rig(tmp))
        r.key(r.HELP)
        assert r.m.csr & hb.CSR_OSM
        assert r.m.osm_xy == (20 << 8) and r.m.osm_dxdy == (25 << 8 | 28)
        assert not r.m.csr & hb.CSR_KBD and r.m.csr & hb.CSR_JOY1 and not r.m.csr & hb.CSR_JOY2
        assert r.sh.filter_input([0xFF] * 9, 0x30) == ([0] * 9, 0)
        rows = r.screen()
        r.show('main menu')
        assert rows[0][20:45] == '+' + '=' * 23 + '+'
        assert rows[1][20:45] == '| Amiga 500             |'
        assert rows[3][20:45] == '|*ADF:<Load>            |'.replace('*', ' ')
        assert any('Linux Module' in row for row in rows)
        assert any('RAM: 512K+512K Slow' in row for row in rows)
        # headline colour, cursor on the ADF line (OPTM_G_START)
        assert r.m.vram[1][1 * 45 + 21] == ui.SA_TTLE
        assert r.m.vram[1][3 * 45 + 21] == ui.SA_STD_INV
        r.key(r.HELP)
        r.run(0.5)
        assert not r.m.csr & hb.CSR_OSM and r.m.csr & hb.CSR_KBD
        assert not os.path.exists(os.path.join(r.dir, 'amiga.settings')), 'nothing changed: no write'


def nav_to(r, text):
    """move the cursor down until the highlighted line contains text"""
    for _ in range(40):
        rows = r.screen()
        for y in range(36):
            if r.m.vram[1][y * 45 + 21] == ui.SA_STD_INV:
                if text in rows[y]:
                    return
        r.key(r.DOWN)
    raise AssertionError('menu line %r not reached' % text)


def test_topology_change_holds_the_core():
    with tmpdir() as tmp:
        r = started(Rig(tmp))
        r.key(r.HELP)
        nav_to(r, 'RAM:')
        r.key(r.RETURN)
        r.show('RAM submenu')
        nav_to(r, '2 MB Fast RAM')
        n0 = len(r.m.events)
        r.key(r.RETURN)
        ev = r.m.events[n0:]
        assert [e[0] for e in ev] == ['hold', 'release'], ev
        assert not [e for e in ev if e[0] == 'cfm_while_running']
        c = json.loads(menu_data()[0])['c_menu']
        assert r.m.cfm[c['FAST_2M'] // 16] >> (c['FAST_2M'] % 16) & 1
        assert not r.m.cfm[c['FAST_NONE'] // 16] >> (c['FAST_NONE'] % 16) & 1
        r.key(r.RUNSTOP)                        # back to the main menu
        rows = r.screen()
        assert any('RAM:' in row for row in rows)
        r.key(r.HELP)
        r.run(0.5)
        v = st.load(os.path.join(r.dir, 'amiga.settings'))
        assert v['FAST:2 MB Fast RAM'] == 1 and v['FAST:No Fast RAM'] == 0
        # a restart with these settings: the core gets 2 MB fast at the first release
        r2 = Rig(tmp, model=mdl.ModelMaster(menu_id=menu_data()[1], defaults=menu_data()[2]))
        started(r2)
        rel = [e for e in r2.m.events if e[0] == 'release'][0][1]
        assert rel[c['FAST_2M'] // 16] >> (c['FAST_2M'] % 16) & 1


