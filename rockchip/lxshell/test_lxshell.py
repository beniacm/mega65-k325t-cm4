def nav_to(r, text):
    """move the cursor down until the highlighted line contains text"""
    for _ in range(40):
        rows = r.screen()
        for y in range(36):
            if r.m.vram[1][y * 45 + 21] == display.SA_STD_INV:
                if text in rows[y]:
                    return
        r.key(r.DOWN)
    raise AssertionError('menu line %r not reached' % text)


def test_topology_change_holds_the_core():
    with tmpdir() as tmp:
        r = started(Rig(tmp))
        r.key(r.HELP)
        nav_to(r, 'RAM:')
        r.key(r.RETURN)
        r.show('RAM submenu')
        nav_to(r, '2 MB Fast RAM')
        n0 = len(r.m.events)
        r.key(r.RETURN)
        ev = r.m.events[n0:]
        assert [e[0] for e in ev] == ['hold', 'release'], ev
        assert not [e for e in ev if e[0] == 'cfm_while_running']
        c = json.loads(menu_data()[0])['c_menu']
        assert r.m.cfm[c['FAST_2M'] // 16] >> (c['FAST_2M'] % 16) & 1
        assert not r.m.cfm[c['FAST_NONE'] // 16] >> (c['FAST_NONE'] % 16) & 1
        r.key(r.RUNSTOP)                        # back to the main menu
        rows = r.screen()
        assert any('RAM:' in row for row in rows)
        r.key(r.HELP)
        r.run(0.5)
        v = st.load(os.path.join(r.dir, 'amiga.settings'))
        assert v['FAST:2 MB Fast RAM'] == 1 and v['FAST:No Fast RAM'] == 0
        # a restart with these settings: the core gets 2 MB fast at the first release
        r2 = Rig(tmp, model=mdl.ModelMaster(menu_id=menu_data()[1], defaults=menu_data()[2]))
        started(r2)
        rel = [e for e in r2.m.events if e[0] == 'release'][0][1]
        assert rel[c['FAST_2M'] // 16] >> (c['FAST_2M'] % 16) & 1


