def test_adopt_running_machine():
    with tmpdir() as tmp:
        r = started(Rig(tmp))
        r.key(r.HELP)
        r.key(r.RETURN)
        r.key(r.RETURN)                          # mount Workbench.adf
        r.run(0.5)
        r.key(r.HELP)
        r.run(0.5)
        kw, ev = r.m.kick_writes, len(r.m.events)
        # m65d restarts: a new shell on the same (running) hardware
        r2 = Rig(tmp, model=r.m)
        r2.sh.attach()
        r2.run(1.0)
        assert r.m.kick_writes == kw and len(r.m.events) == ev, 'adopt must not touch the machine'
        assert r2.sh.adf and r2.sh.adf.endswith('Workbench.adf')
        assert r2.sh.kbd_to_core
        r.m.amiga_writes(9, bytes([0x33]) * 5632)
        r2.run(3.0)
        with open(os.path.join(r.dir, 'Workbench.adf'), 'rb') as f:
            f.seek(9 * 5632)
            assert f.read(5632) == bytes([0x33]) * 5632


