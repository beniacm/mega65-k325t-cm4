def test_adf_mount_writeback_eject():
    with tmpdir() as tmp:
        r = started(Rig(tmp, adf_files=('Workbench.adf', 'Game.adf', 'notes.txt')))
        r.key(r.HELP)
        r.key(r.RETURN)                         # cursor starts on " ADF:"
        rows = r.screen()
        r.show('browser')
        assert r.m.osm_dxdy == (45 << 8 | 36)
        assert rows[1][1:9] == 'Game.adf' and rows[2][1:14] == 'Workbench.adf'
        assert not any('notes' in row for row in rows)
        r.key(r.DOWN)
        r.key(r.RETURN)
        r.run(0.5)
        m = r.m
        assert bytes(m.adf[:901120]) == r.adfs['Workbench.adf']
        assert m.adf_mounted and m.wbc_wr_en == 1 and m.adf_resp == mdl.RESP_READY
        rows = r.screen()
        r.show('menu with a disk')
        assert any('ADF:Workbench.adf' in row for row in rows)
        # the Amiga writes track 5; after the anti-thrash time the shell writes it back
        new = bytes([0xA5]) * 5632
        m.amiga_writes(5, new)
        r.key(r.HELP)
        r.run(1.0)
        with open(os.path.join(r.dir, 'Workbench.adf'), 'rb') as f:
            f.seek(5 * 5632)
            assert f.read(5632) != new, 'written before the anti-thrash delay'
        r.run(2.5)
        with open(os.path.join(r.dir, 'Workbench.adf'), 'rb') as f:
            f.seek(5 * 5632)
            assert f.read(5632) == new
        assert not any(m.wbc_dirty)
        # SPACE on the ADF line: eject (flushes first)
        m.amiga_writes(7, bytes([0x5A]) * 5632)
        r.key(r.HELP)
        r.key(r.SPACE)
        assert m.adf_req == mdl.REQ_IDLE and not m.adf_mounted and m.wbc_wr_en == 0
        with open(os.path.join(r.dir, 'Workbench.adf'), 'rb') as f:
            f.seek(7 * 5632)
            assert f.read(5632) == bytes([0x5A]) * 5632
        assert any('ADF:<Load>' in row for row in r.screen())
        r.key(r.HELP)


